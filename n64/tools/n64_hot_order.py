#!/usr/bin/env python3
"""Order the paged code so that what runs together sits together.

The N64 build keeps most of its code on the cartridge and reads it in 8 KB
blocks when it is executed (n64/compat/src/pager.c). The linker places
functions in the order of the object files, so the few hundred functions a
race frame calls are spread over the whole 8 MB, a block each, and the pool
of blocks in RAM (1 MB) churns: hundreds of cartridge reads per frame.

A build with -DSTK_N64_PAGER_TRACE=ON logs every address the pager had to
read a block for ("[fault] c0a1b2c4"). This tool maps those addresses to
their functions (and constants) and writes a linker script fragment that
n64/n64_paged.ld includes ahead of everything else: the sections named in
it are placed first, in the order given. Run a race, feed the log, relink,
and repeat: each pass moves what still faulted. Sections already in the
fragment keep their place, new ones are appended.

    n64_hot_order.py <elf> <log> [<log> ...] [--out n64/n64_paged_hot.ld]
                     [--nm mips64-elf-nm] [--from <seconds>]

--from: only faults logged after that time on the console's clock (the
"[... 123.4 s]" log prefix), to leave start-up and loading out.
"""
import argparse
import bisect
import os
import re
import subprocess


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('elf')
    ap.add_argument('logs', nargs='+')
    ap.add_argument('--out', default=os.path.join(
        os.path.dirname(os.path.abspath(__file__)), '..', 'n64_paged_hot.ld'))
    ap.add_argument('--nm', default='/opt/pak-n64/bin/mips64-elf-nm')
    ap.add_argument('--from', dest='start', type=float, default=0.0)
    a = ap.parse_args()

    # symbols of the paged region, by address
    syms = []
    for line in subprocess.run([a.nm, '-n', a.elf], capture_output=True,
                               text=True, check=True).stdout.splitlines():
        p = line.split()
        if len(p) != 3 or p[1] not in 'tTwWrRvV':
            continue
        addr = int(p[0], 16) & 0xFFFFFFFF
        if addr >= 0xC0800000:
            syms.append((addr, p[1], p[2]))
    addrs = [s[0] for s in syms]

    hits = {}
    order = []
    for log in a.logs:
        now = 0.0
        for line in open(log, errors='ignore'):
            line = re.sub(r'\x1b\[[0-9;]*m', '', line)
            t = re.match(r'\[\s*\d+ K.*?([\d.]+) s\]', line)
            if t:
                now = float(t.group(1))
            m = re.match(r'\[fault\] ([0-9a-f]{8})', line)
            if not m or now < a.start:
                continue
            i = bisect.bisect_right(addrs, int(m.group(1), 16)) - 1
            if i < 0:
                continue
            _addr, kind, name = syms[i]
            sect = ('.text.' if kind in 'tTwW' else '.rodata.') + name
            if sect not in hits:
                order.append(sect)
            hits[sect] = hits.get(sect, 0) + 1

    old = []
    if os.path.exists(a.out):
        old = re.findall(r'\*\((\S+)\)', open(a.out).read())
    known = set(old)
    new = [s for s in sorted(order, key=lambda s: -hits[s])
           if s not in known]
    with open(a.out, 'w') as f:
        f.write('/* Generated by n64/tools/n64_hot_order.py: sections placed '
                'first in the paged\n * region, see that tool. */\n')
        for s in old + new:
            f.write('*(%s)\n' % s)
    print('n64_hot_order: %d faults on %d sections; %d new, %d in %s'
          % (sum(hits.values()), len(hits), len(new), len(old) + len(new),
             os.path.relpath(a.out)))


if __name__ == '__main__':
    main()
